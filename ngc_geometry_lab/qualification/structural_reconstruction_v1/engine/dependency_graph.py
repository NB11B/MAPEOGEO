    def __init__(self):
        self.nodes: Dict[str, StructuralNode] = {}
        self.edges: List[StructuralEdge] = []
        self._initialize_master_graph()

    def add_node(self, node: StructuralNode):
        self.nodes[node.id] = node

    def add_edge(self, edge: StructuralEdge):
        self.edges.append(edge)

    def get_primitives(self) -> List[StructuralNode]:
        return [n for n in self.nodes.values() if n.layer == "L0_PRIMITIVE"]

    def get_derived_structures(self) -> List[StructuralNode]:
        return [n for n in self.nodes.values() if n.layer == "L2_DERIVED_STRUCTURE"]

    def audit_coverage(self, target_ids: List[str]) -> Tuple[bool, float, List[str]]:
        missing = [t for t in target_ids if t not in self.nodes]
        coverage = (len(target_ids) - len(missing)) / len(target_ids)
        return (len(missing) == 0, coverage, missing)

